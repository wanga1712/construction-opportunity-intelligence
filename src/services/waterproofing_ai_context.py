def _capital_repair_cycle_features(row: dict[str, Any]) -> dict[str, Any]:
    year = row.get("building_year") or row.get("commissioning_year") or row.get("construction_finish_year")
    try:
        year_int = int(year) if year not in (None, "") else None
    except (TypeError, ValueError):
        year_int = None

    age = row.get("building_age")
    try:
        age_int = int(age) if age not in (None, "") else (2026 - year_int if year_int else None)
    except (TypeError, ValueError):
        age_int = None

    if age_int is None:
        repair_window = "unknown"
        repair_probability_hint = "????? ??? ?????????/?????"
    elif age_int < 12:
        repair_window = "too_new"
        repair_probability_hint = "?????? ??????????? ?????????? ?????????????: ?????? ?????"
    elif age_int < 20:
        repair_window = "early_watch"
        repair_probability_hint = "?????? ??????????: ?????? ???????? ?????? ??? ????????/???????"
    elif age_int < 30:
        repair_window = "medium_watch"
        repair_probability_hint = "??????? ???????????: ????????? ???????????? ????????? ? ??????/???????"
    elif age_int < 50:
        repair_window = "capital_repair_window"
        repair_probability_hint = "??????? ???? ??? ??????????: ????????? 615-??, ???????????? ?????????, ??????? ? ??????????"
    else:
        repair_window = "high_age_priority"
        repair_probability_hint = "??????? ?????????? ??????: ?????? ??????????? ??? ??????? ????????/??/?????? ????????"

    return {
        "capital_repair_cycle": {
            "building_year": year_int,
            "building_age": age_int,
            "repair_window": repair_window,
            "repair_probability_hint": repair_probability_hint,
            "baseline_assumption": "??????????? ????????? ????? ??????????? ??????? ??????? 30 ???, ?? ??????????? ???? ???????? ???????????? ?????????? ? ??????????? ??????????",
        }
    }



def build_waterproofing_ai_prompt(row: dict[str, Any], user_question: str | None = None) -> str:
    """Return a compact prompt for local model calls."""
    payload = build_waterproofing_ai_payload(row)
    question = user_question or (
        "Сформируй краткую CRM-рекомендацию: приоритет, почему объект интересен/неинтересен, "
        "какой первый звонок сделать и какие данные запросить."
    )
    return (
        "Ты AI-советник CRM по гидроизоляции подземных паркингов и подвалов.\n"
        "Не выдумывай факты. Если данных не хватает — явно напиши, чего не хватает.\n"
        "Оцени объект для продаж: контакт, эксплуатация, технический риск, следующий шаг.\n\n"
        "Данные объекта JSON:\n"
        f"{json.dumps(payload, ensure_ascii=False, indent=2)}\n\n"
        f"Запрос пользователя:\n{question}\n\n"
        "Ответ дай структурно: 1) вывод, 2) почему, 3) вопросы заказчику, "
        "4) документы/фото, 5) следующий шаг."
    )

