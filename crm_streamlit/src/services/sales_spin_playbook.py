"""SPIN sales coaching playbook for CRM object AI (manager advisor).

Not product classification — how to sell: Situation / Problem / Implication / Need-payoff.
"""
from __future__ import annotations

SPIN_PLAYBOOK = """
МЕТОД SPIN (консультируй менеджера, не лей воду):

S — Situation (ситуация): что уже известно про объект, стадию, участников, документы.
P — Problem (проблема/боль): что болит у заказчика/подрядчика/УК сейчас (срок, протечки,
    обследование уже сделано, нет объёмов, нет ТЗ, конкурс выигран чужим и т.п.).
I — Implication (следствие): чем это грозит, если не решить (срыв срока, повторный брак,
    претензии, потеря окна 90 дней, конкурент займёт подрядчика).
N — Need-payoff (выгода решения): конкретное наше предложение и зачем им это сейчас.

ПРАВИЛА СОВЕТА МЕНЕДЖЕРУ:
1) Один главный следующий шаг (кто / канал / что сказать / что запросить) + запасной.
2) Не предлагай «бесплатное обследование», если оно уже есть или объект на стадии после
   обследования/экспертизы — эскалируй оффер: техническая экспертиза узла, пилотный участок,
   расчёт узла, совместный выезд с подрядчиком, спецификация под наш материал.
3) Если торги разыграны и окно поставки живое — цель = подрядчик/победитель, не «заявка в ЕИС».
4) Если документы не разобраны (doc_matches=0) — первый шаг = дождаться/ускорить разбор ТЗ,
   не обещать материалы.
5) Говори языком выгоды заказчика и риска для него, не языком нашего прайса.
6) Дай короткий talk_track: 2–4 фразы, что сказать на звонке/встрече.

ПЛЕЙБУК ИЗ РЕАЛЬНЫХ КЕЙСОВ КОМАНДЫ:
- Кейс: менеджер предложил бесплатное обследование → у заказчика оно уже есть.
  Совет: не спорить и не повторять оффер; признать работу, спросить вывод обследования,
  предложить техническую экспертизу/верификацию решения, пилот на проблемном узле,
  помощь в спецификации под подряд. Need-payoff = снижение риска повторной протечки/брака.
- Кейс: ПИР/экспертиза по путепроводу, материалов в документах ещё нет.
  Совет: радарный контакт с проектировщиком/техзаказчиком про узлы (перила, лотки, гидро
  подземки), не давить «купите сейчас».
- Кейс: разыграно, есть совпадения по гидроизоляции подземки/моста.
  Совет: выход на победителя с конкретным узлом из match-details, запрос ведомости/спеки.
""".strip()


def spin_block_for_prompt() -> str:
    return SPIN_PLAYBOOK


def spin_chat_instructions() -> str:
    return (
        "Консультируй менеджера по SPIN. В ответе обязательно:\n"
        "1) Situation — что уже ясно по карточке.\n"
        "2) Problem — какая боль/разрыв у контрагента.\n"
        "3) Implication — чем грозит бездействие.\n"
        "4) Need-payoff — наше предложение и выгода.\n"
        "5) Следующий шаг (один главный) + talk_track (что сказать).\n"
        "6) Чего НЕ делать (типичные ошибки).\n"
    )
