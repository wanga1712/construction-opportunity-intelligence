def priority_letter(score: int) -> str:
    if score >= 75:
        return "A — вести лично"
    if score >= 50:
        return "B — вести в работу"
    if score >= 25:
        return "C — прогрев / отложить"
    return "Архив"


def calculate_score(flags: Dict[str, bool]) -> int:
    mapping = {
        "decision_maker": 20,
        "mobile": 10,
        "active_leak": 15,
        "documents": 10,
        "site_access": 15,
        "check_3m": 10,
        "check_10m": 20,
        "tz_influence": 20,
        "competition": -15,
        "no_contact": -20,
    }
    score = sum(points for key, points in mapping.items() if flags.get(key))
    return max(0, min(100, score))


