def main() -> int:
    data = {"keywords": []}
    if TARGET.exists():
        data = json.loads(TARGET.read_text(encoding="utf-8"))
    existing = [str(x).strip() for x in data.get("keywords") or [] if str(x).strip()]
    seen = {x.lower() for x in existing}
    added = 0
    for phrase in LIGHTING_KEYWORDS:
        key = phrase.lower()
        if key in seen:
            continue
        existing.append(phrase)
        seen.add(key)
        added += 1
    TARGET.write_text(
        json.dumps({"keywords": existing}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"keywords_total={len(existing)} lighting_added={added} path={TARGET}")
    print("STOP_PHRASES=" + "||".join(LIGHTING_STOP_PHRASES))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
